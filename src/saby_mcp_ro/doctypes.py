BY_CODE: dict[str, DocType] = {}
for _t in ALL_TYPES:
    # Первое совпадение побеждает: СчетИсх и СчетВх называются по-русски
    # одинаково, и код у них разный, а ключём служит код.
    BY_CODE.setdefault(_t.code, _t)

VERIFIED: tuple[DocType, ...] = tuple(t for t in ALL_TYPES if t.verified)
UNVERIFIED: tuple[DocType, ...] = tuple(t for t in ALL_TYPES if not t.verified)

CATEGORIES: dict[str, tuple[DocType, ...]] = {}
for _t in ALL_TYPES:
    CATEGORIES.setdefault(_t.category, []).append(_t)


def is_known(code: str) -> bool:
    return code in BY_CODE


def describe(code: str) -> DocType | None:
    return BY_CODE.get(code)


def _norm(text: str) -> str:
    return text.lower().replace("ё", "е").strip()


def search(query: str, limit: int = 10) -> list[DocType]:
    """Найти типы по русскому описанию или по внутреннему имени.

    Человек пишет «счёт», «накладная», «фактура» — и должен получить
    `СчетИсх`, `ДокОтгрИсх`, `ФактураИсх`, а не отказ от Saby.

    Сравнение пословное, по основам, а не по подстроке. Наивная подстрока
    здесь давала курьёз: запрос «счет» находился внутри синонима «пересчёт» у
    типа АктИнв, и инвентаризация вставала первым номером в списке счетов.
    """
    from .search import stem, stems, tokens

    query_terms = tokens(query)
    if not query_terms:
        return list(VERIFIED[:limit])
    query_stems = {stem(t) for t in query_terms}

    scored: list[tuple[int, DocType]] = []
    for t in ALL_TYPES:
        code_words = stems(t.code)
        title_words = stems(t.title)
        syn_words = stems(" ".join(t.synonyms))
        cat_words = stems(t.category)

        if query_stems <= code_words:
            score = 100
        elif query_stems <= title_words:
            score = 90
        elif query_stems <= syn_words:
            score = 70
        elif query_stems <= cat_words:
            score = 40
        elif query_stems & code_words:
            score = 30
        elif query_stems & (title_words | syn_words | cat_words):
            score = 20
        else:
            continue
        scored.append((score, t))

    # Сначала подтверждённые: от них больше пользы.
    scored.sort(key=lambda x: (-x[0], not x[1].verified, x[1].code))
    return [t for _, t in scored[:limit]]


def suggest(unknown: str, limit: int = 5) -> list[DocType]:
    """Ближайшие типы к отвергнутому значению.

    Нужны, когда Saby сказал «неизвестный тип документа»: вместо голого отказа
    человек получает то, чем заменить.
    """
    u = _norm(unknown)
    if not u:
        return []
    scored: list[tuple[int, DocType]] = []
    for t in ALL_TYPES:
        candidates = [_norm(t.code), _norm(t.title), *(_norm(s) for s in t.synonyms)]
        best = min((_distance(u, c) for c in candidates), default=99)
        # Отдельная проверка: вхождение как слова — частый случай
        # («счет» внутри «СчетИсх»).
        if any(u == w or u in w for w in candidates):
            best = min(best, 1)
        if best <= max(2, len(u) // 2):
            scored.append((best, t))
    scored.sort(key=lambda x: (x[0], not x[1].verified, x[1].code))
    return [t for _, t in scored[:limit]]


def _distance(a: str, b: str) -> int:
    if a == b:
        return 0
    if not a or not b:
        return len(a) or len(b)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1,
                           prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]
