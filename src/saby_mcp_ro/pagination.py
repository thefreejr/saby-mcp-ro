DEFAULT_MAX_ITEMS = 5_000


def dig(obj: Any, dotted: str) -> Any:
    """Пройти по точечному пути вложенных словарей."""
    cur = obj
    for part in dotted.split("."):
        if isinstance(cur, dict):
            cur = cur.get(part)
        else:
            return None
    return cur


def extract_rows(result: Any, result_key: str) -> list[Any]:
    """Строки выдачи из `result`.

    result_key указывает на ключ верхнего уровня (`Документ`, `Реестр`,
    `СписокПриглашений`...). У части команд (`sabyDepartment.Read`,
    `sabyOurCompany.List`) сам result является массивом — тогда result_key
    пустой и берём его как есть.
    """
    if not result_key:
        return result if isinstance(result, list) else []
    found = dig(result, result_key)
    if isinstance(found, list):
        return found
    if found is None:
        # Ключ не совпал. Берём первый массив, который найдётся: строки лучше,
        # чем ничего, а несовпадение ключа видно в самом ответе.
        for value in _first_list(result):
            return value
        return []
    return []


def _first_list(obj: Any, depth: int = 0) -> list[list[Any]]:
    if depth > 3 or not isinstance(obj, dict):
        return []
    for value in obj.values():
        if isinstance(value, list):
            return [value]
        if isinstance(value, dict):
            found = _first_list(value, depth + 1)
            if found:
                return found
    return []


def server_navigation(result: Any) -> dict[str, Any]:
    """Навигация, которую сервер вернул в ответе."""
    nav = dig(result, "Навигация")
    return nav if isinstance(nav, dict) else {}


def has_more(result: Any) -> bool:
    """Сервер говорит, что есть ещё строки.

    Значение приходит строкой «Да»/«Нет», но на всякий случай понимаем и
    логическое True: контракт меняется между версиями.
    """
    value = server_navigation(result).get("ЕстьЕще")
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        return value.strip().lower() in ("да", "yes", "true", "1")
    return False


# Потолок Saby. Всё, что больше, молча срезается до него; 5000 и выше дают
# ошибку. Проверено на `СписокИзменений` 15.10.2026: 50 → 50 строк,
# 200 → вся выборка с ЕстьЕще = «Нет», 1000 → молча те же 200.
PAGE_SIZE = "200"
# Корневой объект параметров: у команд он называется по-разному («Фильтр»
# почти у всех), и его задаёт каталог. Навигация должна лежать ВНУТРИ него.
FILTER_ROOTS = ("Фильтр", "Параметр", "Отбор")
# Потолок обхода. Страховка от бесконечного цикла: сервер может вечно
# отвечать «ЕстьЕще = Да» и отдавать одну и ту же страницу. Суммарно через
# fetch_all это ещё и способ разом вытянуть весь аккаунт, а не окно дат.
MAX_PAGES = 60
# Мягкий потолок на ВЕСИну ответа, а не на число строк. Проверено 17.10.2026:
# окно в шесть суток дало 1963 строки и 17,9 МБ JSON — и MCP-сервер на этом
# умер, молча унеся с собой соединение. Обход к этому моменту был полностью
# прав и через CLI отрабатывал нормально; убивало именно то, что такой объём
# положено отдать агенту в одном сообщении.
#
# 2 МБ — это около 450–500 строк: достаточно для любого разумного вопроса и
# заведомо переживает транспорт. Кто хочет больше, пусть сузит период.
OUTPUT_SOFT_LIMIT = 5_000_000


def _with_page_size(params: dict[str, Any],
                    page_size: int | str | None = None,
                    ceiling: int | None = None) -> dict[str, Any]:
    """Вложить запрошенный размер страницы в корневой объект фильтра.

    Копия, а не мутация: объект фильтра у команды может быть общим. Слияние
    глубокое — через `_merge`, иначе «РазмерСтраницы» затёр бы «Страница».

    Потолок — не общий для всех. Справка даёт разные числа: 200 у реестра,
    50 у задач и у СписокИзменений, 20 у служебных этапов. Просить больше
    бессмысленно, сервер срежет сам, а мы бы не знали, сколько на самом деле
    пришло.

    Если корневого объекта нет — команда его и не принимает, и `with_root`
    отдала пустые параметры. Добавлять «Фильтр» от себя нельзя: это ломает
    контракт, который проверяет test_command_without_root_stays_empty.
    """
    size = str(page_size) if page_size else "200"
    try:
        wanted = int(size)
    except (TypeError, ValueError):
        return params
    cap = int(ceiling) if ceiling else 200
    if wanted > cap:
        size = str(cap)
    return _merge(params, {"Навигация": {"РазмерСтраницы": size}})


async def fetch_all(
    client: SabyClient,
    command_id: str,
    params: dict[str, Any] | None = None,
    page_size: int | None = None,
    max_items: int = DEFAULT_MAX_ITEMS,
    max_pages: int = MAX_PAGES,
) -> dict[str, Any]:
    """Получить все строки команды.

    Страница запрашивается явно: `Навигация.РазмерСтраницы` внутри корневого
    объекта поднимает порцию с 25 до потолка Saby (200). Дальше обход идёт
    по страницам — способ зависит от команды, см. `_advance` и
    `Command.pagination_mode`. У команд с `pagination_mode = "none"` отдаётся
    одна страница, и об этом честно пишется в notes.

    Гарантии, ради которых обход и писался:
      • `truncated` поднимается только когда сервер прямо сказал «ЕстьЕще»
        или упёрлись в `max_items`, а не просто потому, что строк много;
      • обход конечен: страниц не больше `MAX_PAGES`, а повтор курсора
        обрывает цикл — иначе сервер, отдающий одну и ту же страницу, завёл
        бы нас в бесконечный круг;
      • строки не задваиваются: дедупликация по идентификатору.

    Возвращает {"ok", "items", "total_fetched", "pages_fetched",
    "truncated", "server_navigation", "notes"?}.
    """
    cmd = catalog.get(command_id)
    if cmd is None:
        raise SabyError(f"Не знаю команду {command_id!r}.")

    max_items = max(1, max_items)
    base = catalog.with_root(cmd, params)
    # Если в кабинете несколько организаций, а вызывающий не сказал, какая
    # его, — подставляем отбор из config.json. Иначе Saby отдаёт смесь по всем
    # сразу, а с курсором по событию это ещё и риск пропуска. Организацию,
    # заданную вызывающим, не трогаем.
    base = config.scope_filter(base, cmd.accepts_our_company)

    collected: list[Any] = []
    seen: set[str] = set()
    notes: list[str] = []
    pages = 0
    truncated = False
    nav: dict[str, Any] = {}
    stuck: Any = None
    exhausted = False

    # Первую страницу задаём явно: у полного варианта «Навигации» нумерация
    # с нуля, и лучше сказать это прямо, чем полагаться на умолчание сервера.
    if cmd.pagination_mode == "page":
        stuck = {"Навигация": {"Страница": "0"}}

    # Почему обход встал, если встал. Пока это None — выдача кончилась
    # честно, и объявлять усечение незачем.
    stop: str | None = None
    payload_bytes = 0

    while pages < max_pages and len(collected) < max_items:
        result = await client.call_command(
            cmd.id, _with_page_size(_merge(base, stuck), page_size,
                                    ceiling=cmd.page_size_max))
        rows = extract_rows(result, cmd.result_key)
        nav = server_navigation(result)
        pages += 1
        payload_bytes += _weight(rows)
        collected.extend(r for r in rows if _not_seen(r, seen))

        if not has_more(result):
            exhausted = True
            break
        if not rows:
            # «ЕстьЕще = Да», но строк нет: продолжать нечем и незачем.
            exhausted = True
            break

        step = _advance(cmd, result, rows)
        if step is None or step == stuck:
            stop = "stuck"
            break
        stuck = step

        if payload_bytes > OUTPUT_SOFT_LIMIT:
            stop = "heavy"
            break
    else:
        # Цикл дошёл до границы сам, а не вырвался.
        stop = "max_pages" if pages >= max_pages else "max_items"

    if not exhausted:
        truncated = True
        if stop == "stuck":
            notes.append(_no_way(cmd, nav))
        elif stop == "max_pages":
            notes.append(
                f"Обход остановлен на {max_pages} страницах — выдача больше не "
                "продвигается. Сузите период."
            )
        elif stop == "heavy":
            notes.append(
                f"Ответ разросся примерно до {payload_bytes / 1e6:.1f} МБ — "
                f"это слишком много для одного вызова агента (потолок "
                f"{OUTPUT_SOFT_LIMIT // 1000000} МБ). Сузите период. Для "
                "вопроса «что изменилось» используйте saby_digest: он "
                "проецирует документы до двадцати полей и отдаёт статистику, "
                "а не сырые строки. Ничего не потеряно, не показана только "
                "часть выдачи."
            )
        else:
            notes.append(
                f"Достигнут предел в {max_items} строк за один вызов — выдача "
                "полнее не показана. Уменьшите период или поднимите max_items."
            )

    if len(collected) > max_items:
        collected = collected[:max_items]
        truncated = True
        notes.append(
            f"Возвращено больше лимита {max_items} строк, лишние отброшены."
        )

    # Доводка по настоящему весу. Оценка выше по выборке пяти строк
    # занижала результат примерно на четверть — строки разной величины, —
    # а решать надо по тому, что действительно уйдёт агенту.
    collected, trimmed = _trim_to_limit(collected)
    if trimmed:
        truncated = True
        notes.append(
            f"Ответ урезан до ~{OUTPUT_SOFT_LIMIT // 1000000} МБ: показаны "
            f"первые {len(collected)} строк. Для сводки используйте "
            "saby_digest — он отдаёт статистику, а не сырые документы."
        )

    out: dict[str, Any] = {
        "ok": True,
        "command": cmd.command,
        "items": collected,
        "total_fetched": len(collected),
        "pages_fetched": pages,
        "truncated": truncated,
        "server_navigation": nav or None,
    }
    if notes:
        out["notes"] = notes
    return out


def _trim_to_limit(rows: list[Any]) -> tuple[list[Any], bool]:
    """Отрезать хвост, пока ответ не влезет в потолок по настоящему весу.

    Считается точный JSON, а не выборка: решать надо по тому, что реально
    уйдёт агенту. Одна сериализация страницы в несколько мегабайт занимает
    десятки миллисекунд — против десятков секунд самого обхода.
    """
    if not rows:
        return rows, False
    size = len(json.dumps(rows, ensure_ascii=False, default=str).encode("utf-8"))
    if size <= OUTPUT_SOFT_LIMIT:
        return rows, False
    # Отрезаем хвост делением пополам: точность не нужна, нужна граница.
    keep = len(rows)
    while keep > 1:
        keep = max(1, keep // 2)
        probe = rows[:keep]
        size = len(json.dumps(probe, ensure_ascii=False,
                              default=str).encode("utf-8"))
        if size <= OUTPUT_SOFT_LIMIT:
            return probe, True
    return rows[:1], True


def _weight(rows: list[Any]) -> int:
    """Примерный вес страницы в байтах.

    Считается по выборке из нескольких строк, помноженной на их число:
    точная сериализация каждой страницы стоила бы дороже, чем сам обход.
    Оценка нужна только чтобы поймать «миллионы строк» до того, как ответ
    уйдёт агенту. Одна проба давала занижение вдвое — строки сильно разные
    по весу, — поэтому берём до пяти, равномерно по странице.
    """
    if not rows:
        return 0
    step = max(1, len(rows) // 5)
    sample = rows[::step][:5]
    average = sum(len(json.dumps(r, ensure_ascii=False, default=str).encode("utf-8"))
                  for r in sample) / len(sample)
    return int(average * len(rows))


def _merge(base: dict[str, Any], step: Any) -> dict[str, Any]:
    """Наложить курсор на копию исходных параметров.

    Курсор кладётся ГЛУБОКО: `Навигация` у курсора и у базы — один и тот же
    ключ, и простой срез `{**base[root], **step}` затирал бы «РазмерСтраницы»
    значением `{«Страница»: ...}`. Слияние сливает по уровням.
    """
    if not step:
        return dict(base)
    root = next((r for r in FILTER_ROOTS if isinstance(base.get(r), dict)), None)
    if root is None:
        # Команда без корневого объекта («СписокАккаунтов», «СписокПодразделений»)
        # Навигацию не примет: на живой проверке СБИС.СписокАккаунтов с «Фильтр»
        # отвечает -32601. Кладём в корень — сломаем и params, и контракт.
        return dict(base)
    merged = dict(base[root])
    for key, value in step.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = {**merged[key], **value}
        else:
            merged[key] = value
    return {**base, root: merged}


def _row_key(row: Any) -> str:
    """Ключ строки для склейки страниц.

    По одному `Идентификатор` дедуплицировать нельзя: у `СписокИзменений` один
    и тот же документ приходит на разных страницах с разными событиями, и это
    РАЗНЫЕ строки — документ получил ещё один этап. Считать их дублями означало
    бы тихо выкинуть события (проверка на живых данных: вместо 200+ строк за
    двое суток оставалось 74).

    Поэтому ключ — документ ВМЕСТЕ с набором его событий. Строка без событий
    (реестр, справочники) склеивается по идентификатору документа, как обычно.
    """
    if not isinstance(row, dict):
        return f"#порядковый:{id(row)}"
    ident = str(row.get("Идентификатор") or "")
    events = row.get("Событие")
    if isinstance(events, list) and events:
        marks = tuple(
            f"{e.get('Идентификатор') or ''}@{e.get('ДатаВремя') or ''}"
            for e in events if isinstance(e, dict)
        )
        if marks:
            return f"{ident}|{marks}"
    return ident or f"#безключевой:{len(ident)}:{ident}{id(row)}"


def _not_seen(row: Any, seen: set[str]) -> bool:
    """Отметить строку и сказать, что её раньше не было.

    Без ключа опознаём строку только по порядковому номеру: такие строки между
    страницами не склеиваются, но и задвоиться не могут.
    """
    key = _row_key(row)
    if not key:
        key = f"#порядковый:{len(seen)}"
    if key in seen:
        return False
    seen.add(key)
    return True


def _no_way(cmd: catalog.Command, nav: dict[str, Any]) -> str:
    """Человекочитаемое объяснение, почему выдача неполная."""
    size = nav.get("РазмерСтраницы")
    tail = f", порция {size} строк" if size else ""
    if cmd.pagination_mode == "none":
        return (
            f"Saby отдала не всё: Навигация.ЕстьЕще = «Да»{tail}. Команда «"
            f"{cmd.command}» поля «Навигация.Страница» не принимает, рабочего "
            "курсора найти не удалось. Сузите период или отбор."
        )
    return (
        f"Saby отдала не всё: Навигация.ЕстьЕще = «Да»{tail}. Обход "
        "остановился: страница не продвигается. Сузите период."
    )


def _advance(cmd: catalog.Command, result: Any, rows: list[Any]) -> Any:
    """Курсор следующей страницы — в терминах самого Saby.

    Возвращает фрагмент корневого объекта параметров, который клиент вложит
    в следующий запрос, либо None, если продолжить нечем.

    Четыре варианта, все выведены из документации и подтверждены живыми
    вызовами 15–16.10.2026:

    «page» (реестр, список документов, наши организации, служебные этапы)
        `Навигация.Страница` — номер страницы с нуля. Реестр за месяц при
        `РазмерСтраницы = 25` отдал со страниц 0, 1 и 2 первые события от
        16.10, 13.10 и 09.10 — смещение настоящее, а не эхо.

    «position» (`СБИС.СписокЗадач`)
        `Навигация.Позиция.ДатаВремя` из `Навигация.СледующаяПозиция`.
        Раньше это поле сочли нерабочим, потому что проверили его на
        `СписокИзменений`, у которого позиции нет вообще.

    «event_cursor» (`СБИС.СписокИзменений`)
        `Фильтр.ИдентификаторСобытия` + `Фильтр.ДатаВремяС`. Кладётся
        `Событие.Идентификатор` ПОСЛЕДНЕЙ строки, а не `Документ.Идентификатор`
        — с идентификатором документа сервер отвечает иначе, и на этом
        когда-то и вырос ложный вывод «курсор не работает».

        Пункт 12 справки changeslist требует при курсоре ещё и
        `Фильтр.НашаОрганизацию`: «иначе можно пропустить событие». Но
        подставлять её из данных НЕЛЬЗЯ — это не уточнение позиции, а фильтр:
        на живых данных 16.10.2026 курсор с `НашаОрганизация`, взятым из
        предыдущей страницы, вернул 254 события вместо 260, молча выкинув
        события второй организации (у нас их две). Поэтому организация
        протаскивается только та, которую задал вызывающий, а если в аккаунте
        организаций несколько и она не задана — обход пишет об этом в notes,
        чтобы ограничение курсора было видно, а не спрятано.

    «invitation_cursor» (`СБИС.СписокИзмененийПриглашений`)
        Заявлен справкой (`Фильтр.ИдентификаторПриглашения`), и сервер поле
        принимает — но выдачу не двигает: повторный запрос с идентификатором
        последнего приглашения вернул то же окно и закончился тем же
        идентификатором (проверено 16.10.2026). Ветка оставлена, но команда
        помечена «none»: работающего курсора нет.

    Чего пробовать НЕ надо:
      `Навигация.Позиция.ДатаВремя` у команд без позиции,
      `Навигация.НачальнаяПозиция`, `Навигация.Страница` у `СписокИзменений`.
    """
    if cmd.pagination_mode == "page":
        return {"Навигация": {"Страница": str(int(safe_page(result)) + 1)}}
    if cmd.pagination_mode == "position":
        stamp = next_position(result)
        return {"Навигация": {"Позиция": {"ДатаВремя": stamp}}} if stamp else None
    if cmd.pagination_mode == "event_cursor":
        moment, event_id = last_event(rows)
        if not event_id:
            return None
        return {"ИдентификаторСобытия": event_id, "ДатаВремяС": moment}
    if cmd.pagination_mode == "invitation_cursor":
        ident = ""
        for row in reversed(rows or []):
            if isinstance(row, dict) and row.get("ИдентификаторПриглашения"):
                ident = str(row["ИдентификаторПриглашения"])
                break
        return {"ИдентификаторПриглашения": ident} if ident else None
    return None


def next_position(result: Any) -> str:
    """`Навигация.СледующаяПозиция.ДатаВремя` — позиция следующей страницы."""
    pos = server_navigation(result).get("СледующаяПозиция")
    if isinstance(pos, dict):
        return str(pos.get("ДатаВремя") or "")
    return ""


def last_our_org(rows: list[Any]) -> dict[str, Any] | None:
    """`НашаОрганизация` последней строки — как велит п.12 справки."""
    for row in reversed(rows or []):
        if isinstance(row, dict):
            org = row.get("НашаОрганизация")
            if isinstance(org, dict) and org:
                return org
    return None


def safe_page(result: Any) -> int:
    """Номер страницы, на которой мы находимся (по умолчанию 0)."""
    value = server_navigation(result).get("Страница")
    try:
        return max(0, int(str(value).strip()))
    except (TypeError, ValueError):
        return 0


def last_event(rows: list[Any]) -> tuple[str, str]:
    """Последнее событие выборки: `(ДатаВремя, Идентификатор)`.

    События лежат внутри документа (`Документ.Событие[]`), а порядок в
    выдаче Saby не гарантирует — поэтому берём максимум по времени, а не
    последний элемент списка. Иначе курсор иногда указывал бы назад и обход
    либо зацикливался, либо терял события.
    """
    best_time, best_id = "", ""
    for row in rows or []:
        if not isinstance(row, dict):
            continue
        events = row.get("Событие")
        if not isinstance(events, list):
            continue
        for event in events:
            if not isinstance(event, dict):
                continue
            when = str(event.get("ДатаВремя") or "")
            ident = str(event.get("Идентификатор") or "")
            if ident and when > best_time:
                best_time, best_id = when, ident
    return best_time, best_id
