def _concepts(raw: Iterable[str]) -> list[set[str]]:
    """Слова запроса → понятия: основа плюс её синонимы.

    Группировка нужна для честного счёта покрытия: «статус» и «состояние» —
    это одно слово человека, а не два. Пока они считались раздельно, метод,
    совпавший с тремя синонимами одного понятия, обгонял метод, совпавший с
    двумя разными понятиями запроса.
    """
    out: list[set[str]] = []
    seen: set[str] = set()
    for raw_token in raw:
        base = stem(raw_token)
        if base in seen:
            continue
        seen.add(base)
        # Синонимы ищем по ЦЕЛОМУ слову, но в группу кладём их основы.
        group = {base} | {stem(w) for syn in _SYNONYMS.get(raw_token, ())
                          for w in (syn,)}
        out.append(group)
    return out


class _Index:
    """Основы слов по командам, разложенные по полям.

    Поля различаются весом. Имя команды — самое надёжное: «СБИС.СписокДокументов»
    буквально содержит слова запроса «список документов». Описание тоже врёт
    редко, но «ИнформацияОСлужебныхЭтапах» описана словами «Список организаций,
    ...служебные документы» и на тот же запрос отвечает не хуже — если не
    понимать, что имя команды весомее. Синонимы нужны, чтобы запрос находился
    не только дословно, но и по смыслу, и поэтому весят меньше всего.
    """

    WEIGHTS = {"command": 1.5, "summary": 1.0, "keywords": 0.8}
    SYNONYM_WEIGHT = 0.5

    def __init__(self) -> None:
        self._by_id: dict[str, dict[str, set[str]]] = {}
        for cmd in catalog.ALL_COMMANDS:
            self._by_id[cmd.id] = {
                "command": stems(cmd.command),
                "summary": stems(cmd.summary),
                "keywords": stems(" ".join(cmd.keywords)),
            }
        self._all: set[str] = set()
        for fields in self._by_id.values():
            for pool in fields.values():
                self._all |= pool

    def fields(self, command_id: str) -> dict[str, set[str]]:
        return self._by_id.get(command_id, {})

    @property
    def vocabulary(self) -> set[str]:
        return self._all


_INDEX: _Index | None = None


def _index() -> _Index:
    global _INDEX
    if _INDEX is None:
        _INDEX = _Index()
    return _INDEX


def search(query: str, limit: int = 8) -> list[catalog.Command]:
    """Команды по свободному тексту, лучшие первыми."""
    idx = _index()
    raw = tokens(query)
    groups = _concepts(raw)
    if not groups:
        return []

    literal = {stem(t) for t in raw}
    scored: list[tuple[float, int, int, str, catalog.Command]] = []
    for cmd in catalog.ALL_COMMANDS:
        fields = idx.fields(cmd.id)
        score = 0.0
        hits = 0
        for group in groups:
            # Слово запроса, попавшее в поле буквально, весит больше, чем
            # попавшее туда же через синоним.
            best = 0.0
            for field, weight in idx.WEIGHTS.items():
                pool = fields.get(field, set())
                if (group & literal) & pool:
                    best = max(best, weight)
                elif group & pool:
                    best = max(best, idx.SYNONYM_WEIGHT)
            if best:
                hits += 1
                score += best
        if not hits:
            continue
        # Покрытие запроса, а не частота: совпадение двух слов из трёх
        # ценнее, чем одного.
        score += 2.0 * hits / len(groups)
        # Разрыв ничьей: сколько лишних слов в имени команды не покрыто
        # запросом. На «список сертификатов» и «СБИС.СписокСертификатов», и
        # «СБИС.СписокСертификатовДляАутентификации» совпадают оба слова с
        # одинаковым весом, и без этого разрыва верх брала более короткое
        # описание — то есть не та команда.
        surplus = len(fields.get("command", set()) - literal)
        scored.append((score, surplus, len(cmd.summary), cmd.id, cmd))

    scored.sort(key=lambda x: (-x[0], x[1], x[2], x[3]))
    return [c for _, _, _, _, c in scored[:limit]]


def suggest(unknown: str, limit: int = 5) -> list[str]:
    """Ближайшие слова словаря — когда запрос не дал результата.

    Отвечает не «ничего не найдено», а «вы, может, имели в виду вот это»,
    потому что пустой ответ агент обычно трактует как поломку сервера.
    """
    idx = _index()
    vocab = idx.vocabulary
    if not vocab:
        return []
    base = stem(unknown)
    near: list[tuple[int, str]] = []
    for word in vocab:
        dist = _levenshtein(base, word)
        if dist <= max(2, len(base) // 3):
            near.append((dist, word))
    near.sort()
    return [w for _, w in near[:limit]]


def _levenshtein(a: str, b: str) -> int:
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]
