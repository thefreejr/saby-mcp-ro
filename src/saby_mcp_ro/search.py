"""Поиск команд по словам на русском и английском.

Отличия от наивного совпадения подстрок, которые здесь и были источником
ошибок в изученном сервере:

1. Основы считаются ПРАВИЛЬНО с обеих сторон. Там `stem('подпиши')` давало
   «подпиш», а `stem('подписать')` — «подпис»: одна буква, а слова уже не
   совпадали, и команда подписи не находилась никогда. Здесь основы
   приводятся к общему виду отсечением нормализованного окончания, и
   «подпиши»/«подписать»/«подпись» сходятся в одну.

2. operation_id намеренно НЕ участвует в поиске. Он транслитерирован в
   латиницу (sbis_podpisat_vlozhenie), поэтому русское слово из запроса
   никогда с ним не сойдётся. Индексируется только то, на чём говорит
   человек: кириллическое имя команды, описание и синонимы.

3. Покрытие запроса важнее частоты. Запрос из двух слов, где совпали оба,
   обязан стоять выше запроса, где совпало одно, даже если это одно
   встретилось десять раз.
"""
