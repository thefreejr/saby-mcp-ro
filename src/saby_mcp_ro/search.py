# Окончания от длинных к коротким: иначе «ами» не сработает, потому что
# «и» срежется раньше.
# Порядок решает всё: окончания проверяются от длинных к коротким, иначе
# «ать» срежется раньше «ывать» и «подписывать» превратится в «подписыв».
# Гласная в конце инфинитива («ывать») отнесена выше «ать» сознательно.
_RU_ENDINGS: tuple[str, ...] = (
    "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
    "ность", "ость", "ешь", "ует", "уют", "ают",
    "ывать", "овать", "ивать", "ать", "ять", "ить", "еть", "ыть",
    "ться", "тся",
    "ие", "ия", "ые", "ая", "яя", "ое", "ее", "ый", "ий",
    "ей", "ой", "ов", "ев", "ем", "ам", "ям", "ах", "ях", "ом",
    "ла", "ло", "ли", "ил",
    "а", "я", "е", "о", "у", "ю", "ы", "и", "ь", "й",
)
# «e» в конце нужен, чтобы «certificate» и «certificates» сошлись: без него
# первое остаётся «certificate», а второе срезается до «certificat».
_EN_ENDINGS: tuple[str, ...] = ("ing", "ies", "ed", "es", "s", "e")

_WORD = re.compile(r"[^0-9A-Za-zА-Яа-яЁё]+")
_HAS_CYRILLIC = re.compile(r"[а-яё]")


def stem(token: str) -> str:
    """Слово → грубая основа.

    Отсекает одно окончание, затем добирает одну гласную: «документы» после
    первого прохода это «документ», а «документом» — «документм», и без
    добора падежи не сойдутся. Второе многобуквенное окончание снимать нельзя
    («рекламы» превратилось бы в «рекл»).
    """
    t = token.lower().replace("ё", "е")
    endings = _RU_ENDINGS if _HAS_CYRILLIC.search(t) else _EN_ENDINGS
    if endings is _EN_ENDINGS and t.endswith("ies") and len(t) - 3 >= MIN_STEM:
        t = t[:-3] + "y"
    elif endings is _EN_ENDINGS and t.endswith("ves") and len(t) - 3 >= MIN_STEM:
        t = t[:-3] + "f"  # knives → knife
    for end in endings:
        if len(t) > MIN_STEM and t.endswith(end) and len(t) - len(end) >= MIN_STEM:
            t = t[: -len(end)]
            break
    if endings is _RU_ENDINGS and len(t) > MIN_STEM and t[-1] in "аеиоуыэюяьй":
        t = t[:-1]
    return t


def tokens(text: str, drop_stopwords: bool = True) -> list[str]:
    """Текст → слова. Змеиный и вербёжий регистр разбираются на части.

    Служебные слова по умолчанию убираются: см. _STOPWORDS.
    """
    spaced = re.sub(r"(?<=[a-zа-я])(?=[A-ZА-Я])", " ", text)
    out = [t for t in _WORD.split(spaced.lower()) if t]
    if drop_stopwords:
        out = [t for t in out if t not in _STOPWORDS]
    return out


def stems(text: str) -> set[str]:
    return {stem(t) for t in tokens(text)}


